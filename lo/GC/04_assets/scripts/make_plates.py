def lao(ch, anchor, start, end):
    """The caption text, copied from the paragraph {GC anchor} of chapter ch."""
    t = (PUBLIC / f"GC{ch:02d}_lo.md").read_text(encoding="utf-8")
    m = re.search(r"## \{GC " + re.escape(anchor) + r"\}\n(.*?)(?=\n## \{GC |\Z)", t, re.S)
    if not m:
        raise SystemExit(f"no paragraph {{GC {anchor}}} in GC{ch:02d}")
    p = m.group(1)

    def copy(start, end):
        i = p.find(start)
        if i < 0:
            raise SystemExit(f"start text not found in {{GC {anchor}}}: {start}")
        if end is None:
            return start
        j = p.find(end, i)
        if j < 0:
            raise SystemExit(f"end text not found in {{GC {anchor}}}: {end}")
        return p[i:j + len(end)]

    if end == "":
        return "".join(copy(*piece.split("..")) if ".." in piece else piece for piece in start.split("|"))
    return copy(start, end)


def tex_safe(s):
    if re.search(r"[\\{}$&#^_%~]|\[\^", s) or s.count("*") % 2:
        raise SystemExit(f"caption needs TeX or Markdown handling: {s}")
    return s


dictionaries = {}


def line_breaks(ch, s):
    """The caption with its Lao words marked for line breaking, as modules 1 and 2 mark the body
    text: the repetition mark becomes \\laorepeat, then module 2 marks the words."""
    if ch not in dictionaries:
        with contextlib.redirect_stdout(io.StringIO()):
            dictionaries[ch] = m2.load_hierarchical_dictionaries(chapter=f"GC{ch:02d}", book="GC")[0]
    s = handle_lao_repetition_with_context(re.sub(r"\*(.+?)\*", r"\\emph{\1}", s))
    text = m2.process_text_line(s, dictionaries[ch])
    # \nobreak removes the skip before it; the body text has \textspace there, whose own
    # zero skip is what goes, but a plain space would be lost (as before an italic phrase)
    text = text.replace(" \\nobreak{}", "\\textspace{}\\nobreak{}")
    if "\\nodict" in text:
        raise SystemExit(f"caption has a word the dictionaries cannot segment: {text}")
    return text


